#include "ShareFingerprint.h"
#include "core/CustomData.h"
#include "core/Entry.h"
#include "core/Group.h"
#include "crypto/CryptoHash.h"
#include "keeshare/KeeShareSettings.h"

#include <QtEndian>

#include <algorithm>

namespace
{
    class Hasher
    {
    public:
        Hasher()
            : m_hash(CryptoHash::Sha256)
        {
        }

        Hasher& operator<<(qint64 value)
        {
            const auto bigEndian = qToBigEndian(value);
            m_hash.addData(QByteArray(reinterpret_cast<const char*>(&bigEndian), sizeof(bigEndian)));
            return *this;
        }

        Hasher& operator<<(bool value)
        {
            return *this << static_cast<qint64>(value);
        }

        Hasher& operator<<(int value)
        {
            return *this << static_cast<qint64>(value);
        }

        Hasher& operator<<(const QByteArray& value)
        {
            // Length prefix keeps adjacent fields from running into each other
            *this << static_cast<qint64>(value.size());
            m_hash.addData(value);
            return *this;
        }

        Hasher& operator<<(const char* value)
        {
            return *this << QByteArray(value);
        }

        Hasher& operator<<(const QString& value)
        {
            return *this << value.toUtf8();
        }

        Hasher& operator<<(const QUuid& value)
        {
            return *this << value.toRfc4122();
        }

        Hasher& operator<<(const QDateTime& value)
        {
            // Containers store whole seconds only
            return *this << (value.isValid() ? value.toSecsSinceEpoch() : qint64(-1));
        }

        QByteArray result() const
        {
            return m_hash.result();
        }

    private:
        CryptoHash m_hash;
    };

    template <typename T> QList<T*> sortedByUuid(QList<T*> items)
    {
        std::sort(items.begin(), items.end(), [](const T* lhs, const T* rhs) { return lhs->uuid() < rhs->uuid(); });
        return items;
    }

    void addTimeInfo(Hasher& hasher, const TimeInfo& timeInfo)
    {
        // Access time, usage count and location change time are statistics, not shared content
        hasher << timeInfo.creationTime() << timeInfo.lastModificationTime() << timeInfo.expires()
               << timeInfo.expiryTime();
    }

    void addCustomData(Hasher& hasher, const CustomData* customData)
    {
        QStringList keys;
        for (const auto& key : customData->keys()) {
            if (!customData->isAutoGenerated(key)) {
                keys << key;
            }
        }
        keys.sort();
        hasher << keys.size();
        for (const auto& key : keys) {
            hasher << key << customData->value(key);
        }
    }

    void addEntry(Hasher& hasher, const Entry* entry)
    {
        auto tags = entry->tagList();
        tags.sort();

        hasher << "entry" << entry->uuid() << entry->iconNumber() << entry->iconUuid() << entry->foregroundColor()
               << entry->backgroundColor() << entry->overrideUrl() << tags.join(";") << entry->autoTypeEnabled()
               << entry->autoTypeObfuscation() << entry->defaultAutoTypeSequence() << entry->excludeFromReports();
        addTimeInfo(hasher, entry->timeInfo());

        const auto* attributes = entry->attributes();
        const auto attributeKeys = attributes->keys();
        hasher << attributeKeys.size();
        for (const auto& key : attributeKeys) {
            // The protection flag is not compared: writers protect attributes based on database settings
            hasher << key << attributes->value(key);
        }

        const auto* attachments = entry->attachments();
        const auto attachmentKeys = attachments->keys();
        hasher << attachmentKeys.size();
        for (const auto& key : attachmentKeys) {
            hasher << key << attachments->value(key);
        }

        const auto associations = entry->autoTypeAssociations()->getAll();
        hasher << associations.size();
        for (const auto& association : associations) {
            hasher << association.window << association.sequence;
        }

        addCustomData(hasher, entry->customData());
    }

    void addEntries(Hasher& hasher, const Group* group)
    {
        const auto entries = sortedByUuid(group->entries());
        hasher << entries.size();
        for (const auto* entry : entries) {
            addEntry(hasher, entry);
        }
    }

    void addChildren(Hasher& hasher, const Group* parent)
    {
        const auto children = sortedByUuid(parent->children());
        hasher << children.size();
        for (const auto* group : children) {
            // Only the group properties the merger synchronizes; anything else could never converge
            // after an import and would force an export on every save
            hasher << "group" << group->uuid() << group->name() << group->notes() << group->iconNumber()
                   << group->iconUuid() << group->timeInfo().lastModificationTime() << group->timeInfo().expiryTime();
            addEntries(hasher, group);
            addChildren(hasher, group);
        }
    }
} // namespace

QByteArray ShareFingerprint::of(const Group* root, const KeeShareSettings::Reference& reference)
{
    if (!root) {
        return {};
    }
    Hasher hasher;
    // The properties of the root group are not synchronized, only its content
    hasher << reference.password << reference.keepGroups;
    addEntries(hasher, root);
    if (reference.keepGroups) {
        addChildren(hasher, root);
    }
    return hasher.result();
}
